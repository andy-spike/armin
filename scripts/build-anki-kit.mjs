/**
 * Builds the downloadable Anki converter kit and verifies that it matches the
 * checksum in packages/core/src/anki/kit-manifest.json.
 *
 *   pnpm anki:kit                 build, verify, and publish into apps/web/public
 *   pnpm anki:kit:verify          build twice and prove the archive is reproducible
 *   node scripts/build-anki-kit.mjs --update-manifest
 *
 * The generated zip is not committed. `apps/web` runs this script before build
 * and dev, so the web deployment serves the exact artifact the MCP guide names.
 */

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import {
  existsSync,
  copyFileSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { zipSync } from "fflate";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const kitSource = join(root, "tools/anki-kit");
const manifestPath = join(root, "packages/core/src/anki/kit-manifest.json");
const versionPath = join(root, "packages/core/src/anki/kit-version.json");
const outputDir = join(root, "apps/web/public/anki-kit");
const distDir = join(root, "dist/anki-kit");
const tempDir = join(root, ".anki-kit-build");
const webRequire = createRequire(join(root, "apps/web/package.json"));
// Local-time 1980-01-01 is the ZIP epoch and keeps archive bytes stable across
// machines; fflate rejects UTC timestamps that land in 1979 in negative offsets.
const FIXED_MTIME = new Date(1980, 0, 1).getTime();

const args = new Set(process.argv.slice(2));
const updateManifest = args.has("--update-manifest");
const verifyOnly = args.has("--verify");

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

async function bundle() {
  rmSync(tempDir, { recursive: true, force: true });
  mkdirSync(join(tempDir, "kit"), { recursive: true });
  const outfile = join(tempDir, "kit/armin-anki-kit.mjs");
  const bundled = await build({
    entryPoints: [join(kitSource, "cli.ts")],
    outfile,
    absWorkingDir: root,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    sourcemap: false,
    minify: false,
    legalComments: "eof",
    metafile: true,
    logLevel: "silent",
    banner: {
      js: [
        "#!/usr/bin/env node",
        'import { createRequire as __createRequire } from "node:module";',
        'import { fileURLToPath as __fileURLToPath } from "node:url";',
        'import { dirname as __dirnameOf } from "node:path";',
        "const require = __createRequire(import.meta.url);",
        "const __filename = __fileURLToPath(import.meta.url);",
        "const __dirname = __dirnameOf(__filename);",
        "// Generated by scripts/build-anki-kit.mjs. Do not edit.",
      ].join("\n"),
    },
  });
  const notices = new Map();
  for (const input of Object.keys(bundled.metafile.inputs)) {
    if (!input.includes("node_modules/")) continue;
    let directory = dirname(resolve(root, input));
    while (
      !existsSync(join(directory, "package.json")) ||
      !readJson(join(directory, "package.json")).name
    ) {
      const parent = dirname(directory);
      if (parent === directory) throw new Error(`Cannot find package metadata for ${input}`);
      directory = parent;
    }
    const metadata = readJson(join(directory, "package.json"));
    const name = `${metadata.name}@${metadata.version}`;
    if (notices.has(name)) continue;
    const licenses = readdirSync(directory)
      .filter((file) => /^(license|copying)(\.|$)/i.test(file))
      .sort();
    notices.set(
      name,
      [name, ...licenses.map((file) => readFileSync(join(directory, file), "utf8"))].join("\n\n"),
    );
  }
  writeFileSync(
    join(tempDir, "kit/THIRD-PARTY-NOTICES.txt"),
    [...notices]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([, text]) => text)
      .join("\n\n---\n\n"),
  );
  copyFileSync(webRequire.resolve("sql.js/dist/sql-wasm.wasm"), join(tempDir, "kit/sql-wasm.wasm"));
  copyFileSync(join(kitSource, "README.md"), join(tempDir, "kit/README.md"));
  copyFileSync(join(root, "LICENSE"), join(tempDir, "kit/LICENSE"));

  const files = readdirSync(join(tempDir, "kit")).sort();
  // Fixed mtime, deterministic order, and maximum deflate make the archive
  // byte-identical across machines and runs.
  const entries = {};
  for (const name of files) {
    entries[name] = [readFileSync(join(tempDir, "kit", name)), { mtime: FIXED_MTIME, level: 9 }];
  }
  const archive = zipSync(entries, { level: 9 });
  const manifest = readJson(manifestPath);
  const version = readJson(versionPath);
  return {
    archive,
    manifest: {
      ...manifest,
      version: version.version,
      artifact: version.artifact,
      sha256: sha256(archive),
      bytes: archive.byteLength,
    },
    files,
  };
}

function publish(result) {
  const { artifact } = result.manifest;
  for (const dir of [outputDir, distDir]) {
    mkdirSync(dir, { recursive: true });
    for (const name of readdirSync(dir)) rmSync(join(dir, name), { force: true });
    writeFileSync(join(dir, artifact), result.archive);
    writeFileSync(join(dir, `${artifact}.sha256`), `${result.manifest.sha256}  ${artifact}\n`);
  }
  console.log(`Wrote ${relative(root, join(outputDir, artifact))}`);
  console.log(`SHA-256 ${result.manifest.sha256}`);
  console.log(`Files: ${result.files.join(", ")}`);
}

try {
  const first = await bundle();
  if (verifyOnly) {
    const second = await bundle();
    if (
      first.manifest.sha256 !== second.manifest.sha256 ||
      first.archive.byteLength !== second.archive.byteLength
    ) {
      throw new Error("The kit archive is not reproducible: two builds differ.");
    }
  }
  const committed = readJson(manifestPath);
  if (updateManifest) {
    writeFileSync(manifestPath, `${JSON.stringify(first.manifest, null, 2)}\n`);
    console.log(`Updated ${relative(root, manifestPath)}`);
  } else if (
    committed.sha256 !== first.manifest.sha256 ||
    committed.bytes !== first.manifest.bytes
  ) {
    throw new Error(
      `The generated kit does not match ${relative(root, manifestPath)}. ` +
        "Bump the version and run `node scripts/build-anki-kit.mjs --update-manifest`.",
    );
  }
  if (!verifyOnly) publish(first);
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}
